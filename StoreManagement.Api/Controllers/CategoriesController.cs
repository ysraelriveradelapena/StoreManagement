
using System.Security.Claims;
using System.Text.Json;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using StoreManagement.Api.Data;
using StoreManagement.Api.DTOs.Categories;
using StoreManagement.Api.Models;

namespace StoreManagement.Api.Controllers;

[ApiController]
[Route("api/categories")]
[Authorize]
public class CategoriesController : ControllerBase
{
    private readonly ApplicationDbContext _db;

    public CategoriesController(ApplicationDbContext db)
    {
        _db = db;
    }

    // AUDIT LOG HELPER

    private string? CurrentUserId =>
        User.FindFirstValue(ClaimTypes.NameIdentifier)
        ?? User.FindFirstValue("sub");

    private AuditLog CreateAuditLog(
        int categoryId,
        string action,
        object? oldValues,
        object? newValues)
    {
        return new AuditLog
        {
            EntityName = "Category",
            EntityId = categoryId.ToString(),
            Action = action,
            UserId = CurrentUserId,
            CreatedAtUtc = DateTime.UtcNow,

            OldValues = oldValues == null
                ? null
                : JsonSerializer.Serialize(oldValues),

            NewValues = newValues == null
                ? null
                : JsonSerializer.Serialize(newValues),

            IpAddress = HttpContext.Connection.RemoteIpAddress?.ToString()
        };
    }

    // GET ALL CATEGORIES

    [HttpGet]
    public async Task<ActionResult<IEnumerable<CategoryResponse>>> GetCategories(
        [FromQuery] bool includeInactive = false)
    {
        var query = _db.Categories.AsNoTracking();

        if (!includeInactive)
            query = query.Where(x => x.IsActive);

        var result = await query
            .OrderBy(x => x.Name)
            .Select(x => new CategoryResponse
            {
                Id = x.Id,
                Name = x.Name,
                IsActive = x.IsActive,
                CreatedAtUtc = x.CreatedAtUtc,
                UpdatedAtUtc = x.UpdatedAtUtc
            })
            .ToListAsync();

        return Ok(result);
    }

    // GET CATEGORY BY ID

    [HttpGet("{id:int}")]
    public async Task<ActionResult<CategoryResponse>> GetCategory(int id)
    {
        var category = await _db.Categories
            .AsNoTracking()
            .Where(x => x.Id == id)
            .Select(x => new CategoryResponse
            {
                Id = x.Id,
                Name = x.Name,
                IsActive = x.IsActive,
                CreatedAtUtc = x.CreatedAtUtc,
                UpdatedAtUtc = x.UpdatedAtUtc
            })
            .FirstOrDefaultAsync();

        if (category == null)
            return NotFound(new { message = "Category not found." });

        return Ok(category);
    }

    // CREATE CATEGORY

    [HttpPost]
    [Authorize(Roles = "SystemAdmin")]
    public async Task<ActionResult<CategoryResponse>> CreateCategory(
        CreateCategoryRequest request)
    {
        var name = request.Name?.Trim();

        if (string.IsNullOrWhiteSpace(name))
        {
            return BadRequest(new
            {
                message = "Category name is required."
            });
        }

        var exists = await _db.Categories
            .AnyAsync(x => x.Name == name);

        if (exists)
        {
            return Conflict(new
            {
                message = $"Category '{name}' already exists."
            });
        }

        var category = new Category
        {
            Name = name,
            IsActive = true,
            CreatedAtUtc = DateTime.UtcNow
        };

        // The Category ID is generated by SQL Server.
        // Use one transaction for Category creation and its audit record.

        await using var transaction =
            await _db.Database.BeginTransactionAsync();

        _db.Categories.Add(category);

        await _db.SaveChangesAsync();

        _db.AuditLogs.Add(CreateAuditLog(
            category.Id,
            "CREATE",
            null,
            new
            {
                category.Name,
                category.IsActive
            }));

        await _db.SaveChangesAsync();

        await transaction.CommitAsync();

        return CreatedAtAction(
            nameof(GetCategory),
            new { id = category.Id },
            new CategoryResponse
            {
                Id = category.Id,
                Name = category.Name,
                IsActive = category.IsActive,
                CreatedAtUtc = category.CreatedAtUtc,
                UpdatedAtUtc = category.UpdatedAtUtc
            });
    }

    // UPDATE CATEGORY

    [HttpPut("{id:int}")]
    [Authorize(Roles = "SystemAdmin")]
    public async Task<ActionResult<CategoryResponse>> UpdateCategory(
        int id,
        UpdateCategoryRequest request)
    {
        var category = await _db.Categories.FindAsync(id);

        if (category == null)
        {
            return NotFound(new
            {
                message = "Category not found."
            });
        }

        var name = request.Name?.Trim();

        if (string.IsNullOrWhiteSpace(name))
        {
            return BadRequest(new
            {
                message = "Category name is required."
            });
        }

        var duplicate = await _db.Categories
            .AnyAsync(x => x.Id != id && x.Name == name);

        if (duplicate)
        {
            return Conflict(new
            {
                message = $"Category '{name}' already exists."
            });
        }

        // Do not create audit records for unchanged values.

        if (category.Name == name)
        {
            return Ok(new CategoryResponse
            {
                Id = category.Id,
                Name = category.Name,
                IsActive = category.IsActive,
                CreatedAtUtc = category.CreatedAtUtc,
                UpdatedAtUtc = category.UpdatedAtUtc
            });
        }

        var oldValues = new
        {
            category.Name
        };

        category.Name = name;
        category.UpdatedAtUtc = DateTime.UtcNow;

        _db.AuditLogs.Add(CreateAuditLog(
            category.Id,
            "UPDATE",
            oldValues,
            new
            {
                category.Name
            }));

        // Category update and audit insert are saved together.

        await _db.SaveChangesAsync();

        return Ok(new CategoryResponse
        {
            Id = category.Id,
            Name = category.Name,
            IsActive = category.IsActive,
            CreatedAtUtc = category.CreatedAtUtc,
            UpdatedAtUtc = category.UpdatedAtUtc
        });
    }

    // ACTIVATE / DEACTIVATE CATEGORY

    [HttpPatch("{id:int}/status")]
    [Authorize(Roles = "SystemAdmin")]
    public async Task<IActionResult> UpdateCategoryStatus(
        int id,
        UpdateCategoryStatusRequest request)
    {
        var category = await _db.Categories.FindAsync(id);

        if (category == null)
        {
            return NotFound(new
            {
                message = "Category not found."
            });
        }

        // Avoid duplicate audit entries when status is unchanged.

        if (category.IsActive == request.IsActive)
        {
            return Ok(new
            {
                message = "Category status is already up to date.",
                categoryId = category.Id,
                isActive = category.IsActive
            });
        }

        var oldValues = new
        {
            category.IsActive
        };

        category.IsActive = request.IsActive;
        category.UpdatedAtUtc = DateTime.UtcNow;

        _db.AuditLogs.Add(CreateAuditLog(
            category.Id,
            request.IsActive ? "ACTIVATE" : "DEACTIVATE",
            oldValues,
            new
            {
                category.IsActive
            }));

        await _db.SaveChangesAsync();

        return Ok(new
        {
            message = request.IsActive
                ? "Category activated."
                : "Category deactivated.",

            categoryId = category.Id,
            isActive = category.IsActive
        });
    }
}
